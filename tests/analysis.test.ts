import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { mkdtempSync, rmSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
vi.mock('server-only', () => ({}));
import { context, submit, jobKey, getJob, updateJob, reserveRequest, retryJob, exclusive, jobs, expire, jobFolder, readJson } from '../lib/analysis/store';
import { GET, POST } from '../app/api/analysis/route';
import { GET as jobStatus } from '../app/api/analysis/[key]/route';
import { localAccess } from '../lib/server/analysis';
import { getPositions } from '../lib/server/replay';
import { GET as positionStatus } from '../app/api/positions/[id]/status/route';
const id = '0xa19899f6b8416d8266f0d4f14688c8c6eeaec818:671085802901633847509096';
let folder: string;
beforeEach(() => { folder = mkdtempSync(path.join(os.tmpdir(), 'metric-job-unit-')); vi.stubEnv('LP_ANALYSIS_DIR', folder); vi.stubEnv('LP_ANALYSIS_MODE', 'owner-local'); vi.stubEnv('VERCEL', ''); });
afterEach(() => { vi.unstubAllEnvs(); rmSync(folder, { recursive: true, force: true }); });
describe('durable owner-local admission and protected API', () => {
  it('persists accepted jobs, deduplicates canonical identities and versions, and enforces both caps', () => {
    const c = context(), first = submit(id, c); expect(first.created).toBe(true); expect(first.job.status).toBe('QUEUED');
    expect(readJson(path.join(jobFolder(first.job.key), 'job.json')).id).toBe(id);
    expect(submit(id, c)).toMatchObject({ created: false, job: { key: first.job.key } });
    expect(jobKey(id, { ...c, accountingVersion: 'changed' })).not.toBe(first.job.key);
    const other = getPositions().find(p => p.id !== id)!; submit(other.id, c);
    expect(() => submit(getPositions().find(p => p.id !== id && p.id !== other.id)!.id, c)).toThrow('daily quota');
    for (let i = 0; i < 100; i++) reserveRequest(first.job.key);
    expect(getJob(first.job.key)?.requests).toBe(100);
    expect(() => reserveRequest(first.job.key)).toThrow('budget exhausted');
    updateJob(first.job.key, { status: 'FAILED' }); expect(() => retryJob(first.job.key)).toThrow('exhausted');
    expect(readJson(path.join(folder, 'budget.json')).issued).toBe(100);
  });
  it('protects one-worker concurrency, cancellation, bounded retry and expiration', () => {
    const release = exclusive('worker'); expect(() => exclusive('worker')).toThrow(); release();
    const job = submit(id).job; reserveRequest(job.key);
    updateJob(job.key, { status: 'FAILED', cancelled: true }); expect(() => reserveRequest(job.key)).toThrow('cancelled');
    expect(() => updateJob(job.key, { status: 'VERIFIED' })).toThrow('Cancelled job cannot be promoted');
    expect(retryJob(job.key)).toMatchObject({ status: 'QUEUED', requests: 1, cancelled: false });
    updateJob(job.key, { attempts: 3, status: 'FAILED' }); expect(() => retryJob(job.key)).toThrow('exhausted');
    updateJob(job.key, { expiresAt: new Date(0).toISOString() }); expect(getJob(job.key)).toBeNull(); expire(); expect(jobs()).toEqual([]);
    expect(() => jobFolder('../escape')).toThrow('Invalid');
  });
  it('fails closed on Vercel, foreign origins, forwarded remote clients and invalid body/id', async () => {
    const request = (body: unknown, origin = 'http://localhost') => new Request('http://localhost/api/analysis', { method: 'POST', headers: { 'content-type': 'application/json', origin }, body: JSON.stringify(body) });
    expect((await POST(request({ positionId: id }, 'https://foreign.example'))).status).toBe(403);
    expect(localAccess(new Request('http://localhost', { headers: { 'x-forwarded-for': '203.0.113.2' } }))).toBe(false);
    expect(localAccess(new Request('http://localhost:3100', { headers: { host: '127.0.0.1:3100', 'x-forwarded-host': '127.0.0.1:3100', origin: 'http://127.0.0.1:3100', 'content-type': 'application/json' } }), true)).toBe(true);
    expect(localAccess(new Request('http://localhost:3100', { headers: { host: 'foreign.example:3100' } }))).toBe(false);
    vi.stubEnv('VERCEL', '1');
    expect((await POST(request({ positionId: id }))).status).toBe(403);
    expect((await (await GET(new Request('http://localhost/api/analysis'))).json()).queueAvailable).toBe(false);
    expect(jobs()).toEqual([]); vi.stubEnv('VERCEL', '');
    expect((await POST(request(null))).status).toBe(400);
    expect((await POST(request({ positionId: '../escape' }))).status).toBe(400);
    expect((await POST(request({ positionId: '0x000000000000000000000000000000000000dead:0' }))).status).toBe(404);
    const existing = await POST(request({ positionId: id })); expect(await existing.json()).toMatchObject({ accepted: false, replayAvailable: true, status: 'VERIFIED' }); expect(jobs()).toEqual([]);
    const unpublished = getPositions().find(p => p.status === 'indexed-only')!.id;
    const accepted = await POST(request({ positionId: unpublished })); expect(accepted.status).toBe(202);
    const body = await accepted.json(); expect(body.accepted).toBe(true);
    const position = await positionStatus(new Request('http://localhost/status'), { params: Promise.resolve({ id: unpublished }) });
    expect(await position.json()).toMatchObject({ status: 'QUEUED', queueAvailable: true, progress: { requests: 0 } });
    expect((await jobStatus(new Request('http://localhost/api/analysis/' + body.job.key), { params: Promise.resolve({ key: body.job.key }) })).status).toBe(200);
    expect(JSON.stringify(body)).not.toContain('BNB_RPC_URL'); expect(JSON.stringify(body)).not.toContain('solidrpc');
  });
});
